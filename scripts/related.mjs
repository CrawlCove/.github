#!/usr/bin/env node
// Rewrite the "## Related tools" section of a repo README as one table of every other
// CrawlCove repo, from scripts/descriptions.json, so all READMEs list the same siblings.
//   node scripts/related.mjs <repo-name> <path/to/README.md>
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const [self, readme] = process.argv.slice(2)
const desc = JSON.parse(readFileSync(join(dirname(fileURLToPath(import.meta.url)), 'descriptions.json'), 'utf8'))
// Order: crawl and CI first, then single-purpose checkers, then data formats, then integrations.
const ORDER = [
  'seo-crawler-cli', 'seo-audit-action', 'seo-mcp-server', 'claude-seo-plugin', 'seo-chrome-extension',
  'xml-sitemap-validator', 'robots-txt-tester', 'redirect-chain-checker', 'hreflang-checker', 'schema-markup-validator',
  'seo-test-site', 'seo-crawl-export-spec', 'seo-crawl-export-js', 'screaming-frog-export-converter',
  'seo-audit-google-sheets', 'wordpress-seo-connector',
]
for (const k of Object.keys(desc)) if (!ORDER.includes(k)) throw new Error(`descriptions.json has ${k}, add it to ORDER`)
const rows = ORDER.filter((r) => r !== self).map((r) => `| [${r}](https://github.com/CrawlCove/${r}) | ${desc[r]} |`)
const table = `## Related tools\n\n<!-- related:start (generated by CrawlCove/.github scripts/related.mjs) -->\n| Repo | What it does |\n|---|---|\n${rows.join('\n')}\n<!-- related:end -->\n`
let md = readFileSync(readme, 'utf8')
const start = md.indexOf('## Related tools')
if (start < 0) {
  const lic = md.indexOf('\n## License')
  md = lic < 0 ? md.trimEnd() + '\n\n' + table : md.slice(0, lic + 1) + table + '\n' + md.slice(lic + 1)
} else {
  const next = md.indexOf('\n## ', start + 5)
  md = md.slice(0, start) + table + (next < 0 ? '' : '\n' + md.slice(next + 1))
}
writeFileSync(readme, md)
console.log(`${readme}: ${rows.length} related repos`)
